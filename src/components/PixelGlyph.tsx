export function PixelGlyph({
  name,
  size = 16,
  color,
  className = "",
}: {
  name: PixelGlyphName;
  size?: number;
  color?: string;
  className?: string;
}) {
  const ref = useRef<HTMLCanvasElement>(null);

  useLayoutEffect(() => {
    const canvas = ref.current;
    const ctx = canvas?.getContext("2d");
    if (!canvas || !ctx) return;
    ctx.clearRect(0, 0, 12, 12);
    ctx.imageSmoothingEnabled = false;
    ctx.fillStyle = color ?? getComputedStyle(canvas).color;
    PATTERNS[name].forEach((row, y) => {
      for (let x = 0; x < 12; x += 1) {
        if (row[x] === "#") ctx.fillRect(x, y, 1, 1);
      }
    });
  }, [color, name]);

  return (
    <canvas
      ref={ref}
      width={12}
      height={12}
      className={`pixel-glyph ${className}`}
      aria-hidden="true"
      style={{ width: size, height: size, imageRendering: "pixelated", display: "inline-block", flex: "0 0 auto" }}
    />
  );
}
