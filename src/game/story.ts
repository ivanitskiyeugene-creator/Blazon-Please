// ---------------- ПОСТРОЕНИЕ ВИЗИТА ----------------
export function agentEntrants(dayN: number, flags: Flags, dateShort: string): { at: number; entrant: EntrantSpec }[] {
  const yy = dateShort.slice(-2);
  return VISITS.filter((v) => v.day === dayN)
    .filter((v) => {
      // финальные визиты — только если агент хоть немного «свой»
      if (v.day === 6 && v.agent === "west") return flags.westTrust >= 1;
      if (v.day === 6 && v.agent === "neighbor") return flags.neighborTrust >= 1;
      return true;
    })
    .map((v) => {
      const a = v.agent === "west" ? WEST_AGENT : NEIGHBOR_AGENT;
      const entrant: EntrantSpec = {
        person: a.person,
        dialogue: v.dialogue,
        interrogate: v.interrogate,
        passport: {
          country: a.country,
          name: a.name,
          sex: "M",
          dob: v.agent === "west" ? "03.04.14" : "19.08.09",
          expiry: `28.12.${yy}`,
          id: a.id,
        },
        permit: {
          name: a.name,
          passId: a.id,
          purpose: v.agent === "west" ? "ТОРГОВЛЯ" : "ТОРГОВЛЯ",
          duration: "1 ГОД",
          expiry: `30.09.${Number(yy) + 1}`,
        },
        // западный агент после дня 3 формально невъездной — моральная дилемма
        expected: v.agent === "west" && dayN >= 3 ? "DENY" : "ADMIT",
        cite:
          v.agent === "west" && dayN >= 3
            ? "Гражданам Отеплии въезд запрещён — пропущен агент"
            : "Документы были в порядке — решение без основания",
        mismatch: v.agent === "west" && dayN >= 3 ? [["p.country", "rule.r4"]] : [],
        caught: v.agent === "west" ? "Бумаги, бумаги. Мы же с вами выше бумаг, инспектор." : "Поймали. Ну и что? Я всё равно приду завтра.",
        detainable: false,
        agent: v.agent,
        agentOffer: { prompt: v.prompt, options: v.options },
        reactAdmit: v.agent === "west" ? "До завтра, инспектор." : "Бывайте здоровы. И тепло одевайтесь.",
        reactDeny: v.agent === "west" ? "Ничего. Я найду другое окно." : "Река подождёт. И я подожду.",
      };
      return { at: v.at, entrant };
    });
}

// ---------------- КОНЦОВКИ ----------------
export function pickEnding(flags: Flags, totals: { errors: number; correct: number }) {
  if (flags.finalChoice === "west") return ENDINGS.west;
  if (flags.finalChoice === "neighbor") return ENDINGS.neighbor;
  if (flags.westTrust >= 4 || flags.bribe) return ENDINGS.suspect;
  if (totals.errors <= 6) return ENDINGS.loyal;
  return ENDINGS.shift;
}

